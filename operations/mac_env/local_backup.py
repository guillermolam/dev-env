"""Operator-confirmed local restic bootstrap under the controller state directory."""

import json
import os
import secrets
from pathlib import Path

from mac_env.backup import BackupError, ResticClient, require_password_file_mode
from mac_env.files import atomic_write
from mac_env.runtime import state_dir
from mac_env.validation import require


def bootstrap_local_backup(paths, confirm=False, restic=None, runner=None):
    require(confirm, "local backup bootstrap requires --confirm", BackupError)
    require(bool(paths), "at least one backup path required", BackupError)
    layout = prepare_local_layout(state_dir() / "local-restic", restic)
    snapshot = run_local_backup(layout, paths, runner)
    manifest = write_bootstrap_manifest(layout, paths, snapshot)
    write_env_snippet(layout)
    return bootstrap_result(layout, snapshot, manifest)


def run_local_backup(layout, paths, runner):
    client = ResticClient(layout["config"], runner) if runner else ResticClient(layout["config"])
    maybe_init_repository(client, layout["repo"])
    resolved = [str(Path(path).resolve()) for path in paths]
    snapshot = client.backup(resolved)
    client.verify(snapshot)
    return snapshot


def maybe_init_repository(client, repo):
    if repo.exists() and any(repo.iterdir()):
        return
    client.init_repository()


def bootstrap_result(layout, snapshot, manifest):
    return {
        "ok": True,
        "bootstrap": True,
        "snapshot_id": snapshot,
        "repository": layout["config"]["repository"],
        "password_file": layout["config"]["password_file"],
        "manifest": str(manifest),
        "env_snippet": str(layout["env_snippet"]),
        "note": "Local-only recovery point. Source env_snippet privately; add offsite later.",
    }


def prepare_local_layout(root, restic):
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    password = root / "password"
    ensure_password_file(password)
    repo = root / "repo"
    repo.mkdir(parents=True, exist_ok=True, mode=0o700)
    binary = restic or os.environ.get("MAC_ENV_RESTIC") or "restic"
    config = {
        "repository": str(repo),
        "password_file": str(password),
        "restic": binary,
    }
    return {
        "root": root,
        "repo": repo,
        "password": password,
        "config": config,
        "env_snippet": root / "env.sh",
        "manifest": root / "manifest.json",
    }


def ensure_password_file(path):
    if path.is_file():
        require_password_file_mode(path)
        return
    path.write_text(secrets.token_urlsafe(32) + "\n", encoding="utf-8")
    path.chmod(0o600)
    require_password_file_mode(path)


def write_bootstrap_manifest(layout, paths, snapshot):
    document = {
        "snapshot_id": snapshot,
        "repository": layout["config"]["repository"],
        "paths": [str(Path(path).resolve()) for path in paths],
        "bootstrap": True,
        "offsite": False,
    }
    atomic_write(layout["manifest"], json.dumps(document, indent=2) + "\n")
    return layout["manifest"]


def write_env_snippet(layout):
    text = "\n".join(
        [
            "# Generated by mac-env backup bootstrap-local. Mode 0600. Do not commit.",
            f'export MAC_ENV_RESTIC_REPOSITORY="{layout["config"]["repository"]}"',
            f'export MAC_ENV_RESTIC_PASSWORD_FILE="{layout["config"]["password_file"]}"',
            f'export MAC_ENV_RESTIC="{layout["config"]["restic"]}"',
            "",
        ]
    )
    atomic_write(layout["env_snippet"], text)
    layout["env_snippet"].chmod(0o600)
